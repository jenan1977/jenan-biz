"""
seed_first_article.py – Seeds the first blog article "عالم الثراء وأتمتة الأعمال".

Run from the backend directory:
    PYTHONPATH=. DATABASE_URL=sqlite:///./jenan.db python scripts/seed_first_article.py
"""

import sys
import os

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker

from app.core.config import settings
from app.core.database import Base
import app.models  # noqa: F401

from app.blog import services
from app.blog.schemas import ArticleCreate, CategoryCreate, TagCreate

DATABASE_URL = os.getenv("DATABASE_URL", settings.DATABASE_URL)

engine = create_engine(DATABASE_URL)
Base.metadata.create_all(bind=engine)
Session = sessionmaker(bind=engine, autocommit=False, autoflush=False)
db = Session()

# ---------------------------------------------------------------------------
# Category
# ---------------------------------------------------------------------------
category = services.create_category(
    db,
    CategoryCreate(
        name="الثروة والأعمال",
        slug="wealth-business",
        description="مقالات عن بناء الثروة وتطوير الأعمال",
    ),
)
db.commit()

# ---------------------------------------------------------------------------
# Tags
# ---------------------------------------------------------------------------
tag_names = ["الثراء", "أتمتة الأعمال", "ريادة الأعمال", "الذكاء الاصطناعي", "الاستثمار"]
tags = [services.get_or_create_tag(db, name) for name in tag_names]
db.commit()

# ---------------------------------------------------------------------------
# Article body
# ---------------------------------------------------------------------------
ARTICLE_BODY = """
## ما هو الثراء الحقيقي؟

الثراء الحقيقي ليس مجرد امتلاك المال، بل هو بناء أنظمة تعمل من أجلك حتى وأنت نائم.
في عالم اليوم، أصبح بالإمكان تحقيق ذلك من خلال **أتمتة الأعمال** باستخدام أدوات الذكاء الاصطناعي.

---

## أهمية أتمتة الأعمال في بناء الثروة

أتمتة الأعمال تعني استبدال المهام المتكررة بأنظمة ذكية تعمل تلقائياً.
الفوائد الرئيسية:

- **توفير الوقت**: ما كان يستغرق ساعات أصبح يتم في دقائق.
- **تقليل الأخطاء**: الآلات لا تتعب ولا تخطئ بسبب الإجهاد.
- **قابلية التوسع**: يمكنك خدمة ألف عميل بنفس الجهد الذي كنت تخدم فيه عشرة.
- **التركيز على القيمة**: تحرير وقتك للتفكير الاستراتيجي والإبداعي.

---

## 5 خطوات عملية نحو الثراء عبر الأتمتة

### 1. حدد المهام المتكررة في عملك

ابدأ بتدوين كل المهام التي تقوم بها يومياً وتستغرق وقتاً دون أن تضيف قيمة إبداعية.
مثال: الرد على الأسئلة المتكررة، إرسال الفواتير، تحديث السجلات.

### 2. اختر الأدوات المناسبة

الأدوات الحديثة متاحة للجميع:

- Zapier / Make: ربط التطبيقات
- ChatGPT API: الكتابة والتحليل
- n8n: أتمتة مفتوحة المصدر
- Notion AI: إدارة المعرفة

### 3. ابنِ نموذج دخل سلبي واحداً أولاً

لا تحاول أتمتة كل شيء دفعة واحدة. اختر مصدر دخل واحداً وأتممه:
- **الكورسات الإلكترونية**: تُنتج مرة واحدة وتبيع إلى الأبد.
- **المنتجات الرقمية**: قوالب، كتب، أدوات.
- **خدمة اشتراك**: برنامج أو محتوى بمقابل شهري.

### 4. راقب وحسّن باستمرار

الأتمتة ليست "اضبط وانسَ". راجع أداء أنظمتك كل شهر:

نسبة ROI = (العائد - التكلفة) / التكلفة × 100

مثال: أداة تكلف 50$/شهر وتوفر 10 ساعات عمل بقيمة 500$ → ROI = 900%

### 5. أعِد استثمار الأرباح في المزيد من الأتمتة

كل ريال توفره من خلال الأتمتة، أعده للاستثمار في أنظمة أكثر ذكاءً.
هذا ما يُسمى **دورة الثروة الذاتية**.

---

## حالات دراسية حقيقية

### محمد الريادي – من موظف إلى مليونير رقمي

بدأ محمد بتقديم خدمات كتابة المحتوى يدوياً. بعد دمج ChatGPT API مع نظام إدارة عملاء مؤتمت،
تمكّن من خدمة 50 عميلاً بدلاً من 10، ومضاعفة دخله 5 مرات خلال 8 أشهر.

### شركة ستارتب للتجارة الإلكترونية

أتمتت عمليات خدمة العملاء بالكامل باستخدام روبوت محادثة مدرّب على منتجاتها،
ما أدى إلى توفير 3 موظفين وتحسين رضا العملاء بنسبة 40%.

---

## حسابات وأمثلة مالية

### حساب دخل الأتمتة المتوقع

افترض أنك تملك كورساً رقمياً بسعر 500 ريال:
- **المبيعات المستهدفة**: 20 مبيعة/شهر
- **الدخل الشهري**: 10,000 ريال
- **تكلفة الأتمتة**: 500 ريال/شهر
- **صافي الربح**: 9,500 ريال/شهر
- **ROI السنوي**: 2,280%

---

## الأدوات المستخدمة في جنان بيز

نحن في جنان بيز نوفر لك:

1. **روبوت تحليل المشاريع** – يحلل فكرتك ويقدم خطة عمل كاملة.
2. **روبوت تصميم الدورات** – يبني منهجاً تعليمياً احترافياً.
3. **روبوت التقارير المالية** – يحول بياناتك إلى تقارير قابلة للتنفيذ.

---

## الخلاصة والتوصيات

الثراء في العصر الرقمي يُبنى من خلال ثلاثة محاور:

1. **الأتمتة**: دع الأنظمة تعمل بدلاً عنك.
2. **الحجم**: قابلية التوسع بدون تكاليف خطية.
3. **المعرفة**: الاستثمار المستمر في تعلم الأدوات الجديدة.

**ابدأ اليوم بخطوة واحدة**: حدد المهمة الأكثر تكراراً في يومك وابحث عن أداة تؤتمتها.
"""

# ---------------------------------------------------------------------------
# Create article
# ---------------------------------------------------------------------------
article_data = ArticleCreate(
    title="عالم الثراء وأتمتة الأعمال",
    slug="wealth-and-business-automation",
    summary=(
        "دليل شامل لبناء الثروة من خلال أتمتة الأعمال باستخدام الذكاء الاصطناعي، "
        "مع خطوات عملية وحسابات ROI وحالات دراسية حقيقية."
    ),
    body=ARTICLE_BODY.strip(),
    status="published",
    author="فريق جنان بيز",
    category_id=category.id,
    tag_ids=[t.id for t in tags],
)

article = services.create_article(db, article_data)
db.commit()

print(f"✅ Article created: {article.title!r}")
print(f"   ID:   {article.id}")
print(f"   Slug: {article.slug}")
print(f"   Tags: {[t.name for t in article.tags]}")
